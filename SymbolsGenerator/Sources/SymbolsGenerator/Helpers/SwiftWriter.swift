/// Writes the lines of one Swift scope at a fixed indentation level. Each nested scope gets its own writer, one level
/// deeper, whose lines are added to this one when the scope closes.
struct SwiftWriter {
    /// The brackets that open and close a scope.
    enum Bracket {
        /// `{ … }`: a type, function, accessor or closure body.
        case curly
        /// `[ … ]`: an array or dictionary literal.
        case square

        var opening: String {
            switch self {
                case .curly: "{"
                case .square: "["
            }
        }

        var closing: String {
            switch self {
                case .curly: "}"
                case .square: "]"
            }
        }
    }

    private(set) var code = ""
    private let level: Int
    /// The spaces of one indentation level.
    private let indentationWidth: Int

    private init(level: Int, indentationWidth: Int) {
        self.level = level
        self.indentationWidth = indentationWidth
    }

    /// A generated file: the notice not to edit it, a blank line, then the code `body` writes at the top level.
    /// Every scope in the file is indented by `indentationWidth` spaces per level.
    static func generatedFile(indentationWidth: Int, _ body: (inout SwiftWriter) -> Void) -> String {
        var file = SwiftWriter(level: 0, indentationWidth: indentationWidth)
        file.line("// Don't touch this manually, this code is generated by the SymbolsGenerator helper tool")
        file.blankLine()
        body(&file)
        return file.code
    }

    mutating func line(_ text: String) {
        code += String(repeating: " ", count: level * indentationWidth) + text + "\n"
    }

    mutating func lines(_ texts: [String]) {
        texts.forEach { line($0) }
    }

    mutating func blankLine() {
        code += "\n"
    }

    /// A scope: `header`, the opening bracket (followed by `closureParameters in` when a closure has parameters), the lines `body`
    /// writes, then the closing bracket.
    ///
    /// - Parameter inline: Whether to write the scope on a single line, like `{ self.source = source }` or `[]`, instead
    ///   of putting the content on its own lines one level deeper.
    mutating func scope(
        _ header: String? = nil,
        bracket: Bracket = .curly,
        closureParameters: [String] = [],
        inline: Bool = false,
        _ body: (inout SwiftWriter) -> Void
    ) {
        let parameters = closureParameters.isEmpty ? nil : closureParameters.joined(separator: ", ") + " in"
        let opening = [header, bracket.opening, parameters].compactMap { $0 }.joined(separator: " ")
        var scope = SwiftWriter(level: inline ? 0 : level + 1, indentationWidth: indentationWidth)
        body(&scope)

        guard !inline else {
            let content = scope.code.split(separator: "\n").joined(separator: " ")
            line(content.isEmpty ? opening + bracket.closing : "\(opening) \(content) \(bracket.closing)")
            return
        }
        line(opening)
        code += scope.code
        line(bracket.closing)
    }

    /// Writes each element, with a blank line between them.
    mutating func separated<Elements: Sequence>(_ elements: Elements, _ write: (inout SwiftWriter, Elements.Element) -> Void) {
        for (index, element) in elements.enumerated() {
            if index > 0 {
                blankLine()
            }
            write(&self, element)
        }
    }
}
